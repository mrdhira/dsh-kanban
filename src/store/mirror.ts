/**
 * The generated `tasks/todo.md`.
 *
 * The store is the source of truth and this file is a *view* of it, regenerated on mutation. It
 * exists because the board has to be readable without the app: a phone, a diff, a `cat` over ssh —
 * and because the one-home-per-fact rule needs somewhere honest for the Markdown to live, which is
 * "generated, not authored". The banner says so, and `check-board.mjs` fails when the file on disk
 * diverges from a fresh render, so a hand edit is caught rather than silently lost.
 *
 * Output must be **byte-stable**: same board, same bytes. That is why ordering is fully specified
 * (state order, then expedite, then priority rank, then position, then id) and why every number is
 * formatted through one helper instead of `toLocaleString`, which would make the file depend on
 * the machine's locale.
 */
import type { DefinitionOfWorkflow, Task, TaskFilter } from './types.js';
import { CLASS_LABEL, PRIORITY_LABEL, STATE_LABEL, STATES, WIP_STATES, compareInColumn, stateIndex } from './types.js';
import type { FlowMetrics } from './metrics.js';

const GENERATED_BY = 'dsh-kanban';

/** Deterministic, locale-free number rendering. */
function num(value: number | null): string {
  if (value === null) return '—';
  return Number.isInteger(value) ? String(value) : value.toFixed(2);
}

/**
 * A Markdown link when there is one, the raw ref otherwise.
 *
 * The path is made **relative to this file**, because that is what a Markdown reader resolves
 * against: the mirror lives in `tasks/`, so a folder recorded as `tasks/T-001-slug` becomes
 * `T-001-slug/requirements.md`. Emitting the stored form instead produced links that resolved to
 * `tasks/tasks/…` and were reported broken by `check-links` — the generated file has to be correct
 * for a reader, not merely faithful to the column it came from.
 */
function linkOf(task: Task): string {
  if (task.folder !== null) {
    const relative = task.folder.replace(/^tasks\//, '');
    // A backlog card is a queue entry, not a workspace: its folder may not exist yet, and a generated
    // link to a missing path is a promise the view cannot keep. Path shown, link only once work starts.
    if (task.state === 'backlog') return `\`${relative}/\``;
    return `[${task.id}](${relative}/requirements.md)`;
  }
  const first = task.links[0];
  if (first === undefined) return '—';
  return first.kind === 'url' ? `[link](${first.ref})` : `\`${first.ref}\``;
}

export interface MirrorInput {
  readonly tasks: readonly Task[];
  readonly dow: DefinitionOfWorkflow;
  readonly metrics: FlowMetrics;
  readonly boardTitle: string;
  readonly boardRev: number;
  readonly generatedAt: string;
  readonly invalid?: readonly { readonly id: string; readonly reason: string }[];
  /** The card count in the store, when it is larger than the rows rendered. */
  readonly total?: number;
}

/** Render the whole file. Pure: the same input always produces the same bytes. */
export function renderTodoMd(input: MirrorInput): string {
  const { tasks, dow, metrics, boardTitle, boardRev, generatedAt } = input;

  const ordered = [...tasks].sort((a, b) => {
    const byState = stateIndex(a.state) - stateIndex(b.state);
    return byState !== 0 ? byState : compareInColumn(a, b);
  });

  const lines: string[] = [];
  lines.push(`# ${boardTitle}`);
  lines.push('');
  lines.push(
    `<!-- generated by ${GENERATED_BY} v${boardRev} at ${generatedAt}; edit the board, not this file -->`
  );
  lines.push('');
  lines.push(
    '**Generated view.** The board itself is `board.db` (SQLite). Move cards in the Kanban panel, through the `kanban_*` tools, or with `bin/kanban.mjs`; this file is rewritten from the store, and `check-board.mjs` fails if it drifts.'
  );
  lines.push('');
  lines.push(
    `States: ${STATES.map((state) => `\`${state}\``).join(' → ')} — with \`blocked\` as a flag rather than a column, so blocked work stays counted as WIP.`
  );
  lines.push(
    `WIP control: ${WIP_STATES.map((state) => `${state} ${dow.wip[state]}`).join(', ')}; ready queue cap ${dow.readyCap}. \`expedite\` is the only exception, and only the human may set it.`
  );
  lines.push(
    `SLE: ${Math.round(dow.sle.p * 100)}% of items finish in ${metrics.sle.days} day(s) or less (${metrics.sle.source}${metrics.sle.source === 'history' ? `, from ${metrics.sle.basis} finished` : ', best guess until 10 items finish'}).`
  );
  lines.push('');
  // The write scope rides in the Links cell rather than as a tenth column: `check-board.mjs` reads
  // this table as nine columns, and a generated view that breaks its own checker is not a view. The
  // header keeps its old word, so a board whose cards record no scope renders byte-for-byte as it
  // always did — a renamed header would make every existing `todo.md` look stale on the next check.
  lines.push('| ID | Task | State | Pri | CoS | Owner | Project | Age | Links |');
  lines.push('|---|---|---|---|---|---|---|---|---|');

  for (const task of ordered) {
    const age = task.finishedAt !== null && task.startedAt !== null
      ? `${num(daysOf(task))}d (done)`
      : task.startedAt !== null
        ? `${num(ageAt(task, generatedAt))}d`
        : '—';
    const flags: string[] = [];
    if (task.blockedReason !== null) flags.push(`**blocked**`);
    if (task.exceptions.length > 0) flags.push(`${task.exceptions.length} except.`);
    const title = flags.length > 0 ? `${task.title} ${flags.join(' ')}` : task.title;
    // The scope is a pointer, which is what this cell already holds — and an empty one stays empty
    // rather than printing a second em dash, so the view reads the same for cards without a scope.
    const scope = task.writeScopes.length > 0 ? ` · scope \`${task.writeScopes.join(', ')}\`` : '';
    // The state column carries the **state id**, not the display label. This file is read by
    // `check-board.mjs` as much as by a human, and an id is unambiguous where "In Progress" is a
    // second spelling that can drift from the vocabulary. The header above spells them in order.
    lines.push(
      `| ${task.id} | ${title} | \`${task.state}\` | ${PRIORITY_LABEL[task.priority].split(' ')[0] ?? ''} | ${
        CLASS_LABEL[task.classOfService]
      } | ${task.assignee ?? '—'} | ${task.project ?? '—'} | ${age} | ${linkOf(task)}${scope} |`
    );
  }

  lines.push('');
  lines.push('## Flow metrics');
  lines.push('');
  lines.push(`- **WIP** ${metrics.wip} of ${WIP_STATES.reduce((sum, state) => sum + dow.wip[state], 0)}`);
  lines.push(`- **Throughput** ${metrics.throughput.days7} in 7 days · ${metrics.throughput.days30} in 30 days`);
  lines.push(
    `- **Cycle time** median ${num(metrics.cycle.medianDays)}d · p85 ${num(metrics.cycle.p85Days)}d · mean ${num(
      metrics.cycle.meanDays
    )}d over ${metrics.cycle.count} finished`
  );
  lines.push(
    `- **Work item age** oldest ${metrics.ageing.oldestDays === null ? '—' : `${num(metrics.ageing.oldestDays)}d`} · ${metrics.ageing.count} past the SLE`
  );
  lines.push('');
  lines.push(`Counts: ${STATES.map((state) => `${state} ${metrics.countsByState[state] ?? 0}`).join(' · ')}`);

  if (input.invalid !== undefined && input.invalid.length > 0) {
    lines.push('');
    lines.push('## Rows that failed validation');
    lines.push('');
    for (const entry of input.invalid) lines.push(`- \`${entry.id}\`: ${entry.reason}`);
  }

  // A partly-rendered board must say so, in the file itself. The metrics above are computed from
  // the rows that were read, so a silent cap would make them quietly wrong.
  if (input.total !== undefined && input.total > input.tasks.length) {
    lines.push('');
    lines.push(
      `> **Partial board.** ${input.tasks.length} of ${input.total} cards are shown, and the flow metrics above are computed from those ${input.tasks.length}. Raise the read limit before trusting them.`
    );
  }

  lines.push('');
  return lines.join('\n');
}

function ageAt(task: Task, nowIso: string): number {
  if (task.startedAt === null) return 0;
  return Math.round(((Date.parse(nowIso) - Date.parse(task.startedAt)) / 86_400_000) * 100) / 100;
}

function daysOf(task: Task): number {
  if (task.startedAt === null || task.finishedAt === null) return 0;
  return Math.round(((Date.parse(task.finishedAt) - Date.parse(task.startedAt)) / 86_400_000) * 100) / 100;
}

/** The filter the mirror uses: every live card plus the finished ones, newest first by state. */
export const MIRROR_FILTER: TaskFilter = { limit: 500 };
