/**
 * The generated Markdown mirror.
 *
 * Two properties matter and are both pinned here: it must be **byte-stable** (same board, same
 * bytes — otherwise `check-board.mjs` cannot distinguish a real drift from a formatting wobble),
 * and it must be **locale-free** (a 1,234 vs 1.234 difference would appear only on some machines).
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import {
  DEFAULT_DOW,
  computeFlowMetrics,
  renderTodoMd,
  type Task,
} from '../lib/v1/store/index.js';
import { NOW, makeTask } from './helpers.ts';

function render(tasks: readonly Task[], overrides: Partial<Parameters<typeof renderTodoMd>[0]> = {}): string {
  const metrics = computeFlowMetrics({ tasks, now: NOW, dow: DEFAULT_DOW, boardRev: 7 });
  return renderTodoMd({
    tasks,
    dow: DEFAULT_DOW,
    metrics,
    boardTitle: 'Board',
    boardRev: 7,
    generatedAt: NOW.toISOString(),
    ...overrides,
  });
}

const CARDS: readonly Task[] = [
  makeTask({ id: 'T-002', title: 'second', state: 'backlog', priority: 'p1-high', position: 1 }),
  makeTask({ id: 'T-001', title: 'first', state: 'backlog', priority: 'p3-low', position: 0 }),
  makeTask({
    id: 'T-003',
    title: 'urgent',
    state: 'in-progress',
    priority: 'p4-someday',
    classOfService: 'expedite',
    startedAt: '2026-10-13T12:00:00.000Z',
    position: 0,
  }),
  makeTask({ id: 'T-004', title: 'blocked one', state: 'review', blockedReason: 'waiting on the vendor' }),
];

// ------------------------------------------------------------------ stability

test('the same board renders the same bytes twice', () => {
  assert.equal(render(CARDS), render(CARDS));
});

test('a different board renders different bytes', () => {
  assert.notEqual(render(CARDS), render([...CARDS].slice(0, 2)));
});

test('rendering does not mutate its input', () => {
  const before = CARDS.map((card) => card.id);
  render(CARDS);
  assert.deepEqual(CARDS.map((card) => card.id), before);
});

// ------------------------------------------------------------------ content

test('the header says the file is generated and where the board lives', () => {
  const text = render(CARDS);
  assert.match(text, /^# Board$/m);
  assert.match(text, /generated by dsh-kanban v7/);
  assert.match(text, /The board itself is `board\.db`/);
  assert.match(text, /do not edit|edit the board/i);
});

test('the Definition of Workflow is stated: states, WIP control and the SLE', () => {
  const text = render(CARDS);
  assert.match(text, /States: `backlog` → `ready` → `in-progress` → `review` → `done` → `dropped`/);
  assert.match(text, /WIP control: in-progress 2, review 1; ready queue cap 5/);
  assert.match(text, /SLE: 85% of items finish in 3 day\(s\) or less \(guess/);
});

test('every card appears, including the dropped-by-absence ones', () => {
  const text = render(CARDS);
  for (const card of CARDS) assert.match(text, new RegExp(`\\| ${card.id} \\|`));
});

test('columns are ordered by the board state order, and cards by hand position', () => {
  const text = render(CARDS);
  const backlogFirst = text.indexOf('| T-001 |');
  const backlogSecond = text.indexOf('| T-002 |');
  const inProgress = text.indexOf('| T-003 |');
  const review = text.indexOf('| T-004 |');
  assert.ok(backlogFirst < backlogSecond, 'lower position sorts first, even against a higher priority');
  assert.ok(backlogSecond < inProgress, 'backlog precedes in-progress');
  assert.ok(inProgress < review, 'in-progress precedes review');
});

test('position outranks priority in a column, so a drag is never silently ignored', () => {
  const cards = [
    makeTask({ id: 'T-030', title: 'urgent but second by hand', priority: 'p0-critical', position: 5 }),
    makeTask({ id: 'T-031', title: 'later priority, dragged to the top', priority: 'p4-someday', position: 0 }),
  ];
  const text = render(cards);
  assert.ok(text.indexOf('| T-031 |') < text.indexOf('| T-030 |'));
});

test('priority decides only when no hand position separates two cards', () => {
  const cards = [
    makeTask({ id: 'T-040', title: 'low', priority: 'p3-low', position: 2 }),
    makeTask({ id: 'T-041', title: 'high', priority: 'p0-critical', position: 2 }),
  ];
  const text = render(cards);
  assert.ok(text.indexOf('| T-041 |') < text.indexOf('| T-040 |'));
});

test('an expedite card leads its column regardless of priority', () => {
  const cards = [
    makeTask({ id: 'T-010', title: 'normal', state: 'in-progress', priority: 'p0-critical', position: 0 }),
    makeTask({ id: 'T-011', title: 'expedited', state: 'in-progress', priority: 'p4-someday', classOfService: 'expedite' }),
  ];
  const text = render(cards);
  assert.ok(text.indexOf('| T-011 |') < text.indexOf('| T-010 |'));
});

test('a blocked card is flagged in the title cell', () => {
  assert.match(render(CARDS), /\| T-004 \| blocked one \*\*blocked\*\* \|/);
});

test('the flow metrics are reported, not just the cards', () => {
  const text = render(CARDS);
  assert.match(text, /\*\*WIP\*\* 2 of 3/);
  assert.match(text, /\*\*Throughput\*\* 0 in 7 days · 0 in 30 days/);
  assert.match(text, /\*\*Work item age\*\* oldest 2d/);
});

test('counts are listed for every state', () => {
  const text = render(CARDS);
  assert.match(text, /Counts: backlog 2 · ready 0 · in-progress 1 · review 1 · done 0 · dropped 0/);
});

// ------------------------------------------------------------------ locale independence

test('numbers are rendered without a locale: a dot, and no thousands separator', () => {
  const card = makeTask({
    id: 'T-020',
    title: 'aged',
    state: 'in-progress',
    startedAt: '2026-09-01T12:00:00.000Z',
  });
  const text = render([card]);
  assert.match(text, /44d/, 'a whole number of days has no decimal point');
  assert.doesNotMatch(text, /44,00/);
  assert.doesNotMatch(text, /\u00a0/, 'no non-breaking spaces');
});

// ------------------------------------------------------------------ invalid rows

test('there is no invalid-rows section when nothing failed validation', () => {
  assert.doesNotMatch(render(CARDS), /Rows that failed validation/);
});

test('rows that failed validation are named rather than dropped in silence', () => {
  const text = render(CARDS, { invalid: [{ id: 'T-099', reason: 'unknown state "wibble"' }] });
  assert.match(text, /## Rows that failed validation/);
  assert.match(text, /`T-099`: unknown state "wibble"/);
});

test('an empty board still renders a valid document', () => {
  const text = render([]);
  assert.match(text, /^# Board$/m);
  assert.match(text, /\*\*WIP\*\* 0 of 3/);
  assert.match(text, /\| ID \| Task \|/);
});

test('a partly-read board says so in the file, because its metrics cover only those rows', () => {
  const partial = render(CARDS, { total: 999 });
  assert.match(partial, /Partial board/);
  assert.match(partial, new RegExp(`${CARDS.length} of 999 cards`));

  // A complete read says nothing extra.
  assert.doesNotMatch(render(CARDS, { total: CARDS.length }), /Partial board/);
  assert.doesNotMatch(render(CARDS), /Partial board/);
});

test('a backlog folder is shown, not linked, because its folder may not exist yet', () => {
  // A queued card is not a workspace. Linking a promise the view cannot keep is what put five broken
  // links in the generated file when another session queued cards whose folders were not written yet.
  const queued = makeTask({ id: 'T-010', title: 'queued', state: 'backlog', folder: 'tasks/T-010-queued' });
  const started = makeTask({ id: 'T-011', title: 'started', state: 'in-progress', folder: 'tasks/T-011-started' });

  const text = render([queued, started]);
  assert.match(text, /T-010-queued\//, 'the path is still visible');
  assert.equal(text.includes('[T-010](T-010-queued/requirements.md)'), false, 'but it is not a link');
  assert.match(text, /\[T-011\]\(T-011-started\/requirements\.md\)/, 'a started card keeps its link');
});

// ------------------------------------------------------------------ the write scope

test('write-scope: the generated view carries the scope without adding a tenth column', () => {
  const scoped = makeTask({ id: 'T-050', title: 'scoped', state: 'ready', writeScopes: ['src/store/**', 'test/**'] });
  const text = render([scoped]);
  assert.match(text, /scope `src\/store\/\*\*, test\/\*\*`/, 'the prefixes are in the view');
  assert.match(text, /\| ID \| Task \| State \| Pri \| CoS \| Owner \| Project \| Age \| Links \|/);

  // `check-board.mjs` reads this table as nine columns, so the fact rides in the Links cell rather
  // than becoming a column the checker would refuse. Ten pipes is nine columns.
  const row = text.split('\n').find((line) => line.startsWith('| T-050 '));
  assert.equal((row?.match(/\|/g) ?? []).length, 10, 'nine columns still');

  // A card with no scope renders nothing extra — the empty case is the common case, and the header
  // is deliberately unchanged so an existing `todo.md` with no scoped card stays byte-identical.
  assert.doesNotMatch(render([makeTask({ id: 'T-051', title: 'plain' })]), /scope `/);
  assert.equal(render([makeTask({ id: 'T-052', title: 'plain' })]).includes('Links / scope'), false);
});
